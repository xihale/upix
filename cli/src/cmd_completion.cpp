int cmd_completion(const args::Completion& a) {
    if (a.shell == "bash") {
        std::cout << kBashScript;
    } else if (a.shell == "zsh") {
        std::cout << kZshScript;
    } else if (a.shell == "fish") {
        std::cout << kFishScript;
    } else {
        // Unreachable: cli_app.cpp restricts shell to IsMember({bash,zsh,fish}).
        std::cerr << "unknown shell: " << a.shell << "\n";
        return 1;
    }
    (void)kCommands;  // reserved for future dynamic generation
    return 0;
}
